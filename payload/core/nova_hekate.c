/*
 * NOVA Boot - hekate integration.
 *
 * NOVA never boots Horizon by itself: it hands the boot target to hekate,
 * which is the supported, documented HOS bootloader. The selection is
 * passed through hekate's own "Payload storage" boot_cfg block, the same
 * mechanism modchips use, so NOVA never has to rewrite hekate_ipl.ini.
 *
 * boot_cfg_t layout (hekate bdk/utils/types.h):
 *   0x00 boot_cfg  bit0 autoboot enable, bit1 from launch, bit2 from id
 *   0x01 autoboot
 *   0x02 autoboot_list
 *   0x03 extra_cfg
 *   0x04 id[8] / emummc_path[0x78] / xt_str[0x80]
 *
 * Copyright (c) 2026 NOVA contributors.
 * SPDX-License-Identifier: GPL-2.0-or-later
 */
#include "nova_core.h"

#define HDR_BOOT_CFG   0x00
#define HDR_AUTOBOOT   0x01
#define HDR_AUTOB_LIST 0x02
#define HDR_EXTRA_CFG  0x03
#define HDR_ID         0x04

#define BOOT_CFG_AUTOBOOT_EN 0x01
#define BOOT_CFG_FROM_ID     0x04

static void append(char *out, uint32_t out_size, uint32_t *pos, const char *text)
{
    while (*text && *pos + 1 < out_size)
        out[(*pos)++] = *text++;
    if (out_size)
        out[*pos] = '\0';
}

uint32_t nova_build_hekate_ini(char *out, uint32_t out_size)
{
    if (!out || out_size < 2)
        return 0;

    uint32_t pos = 0;
    out[0] = '\0';

    append(out, out_size, &pos,
           "# NOVA boot entries (generated by NOVA Installer)\n"
           "# These entries are selected by NOVA through hekate's boot_cfg id.\n"
           "# Do not edit: the installer rewrites this file on install.\n"
           "\n"
           "{---- NOVA - Stock ----}\n"
           "[NOVA Stock (SysNAND)]\n"
           "id=" NOVA_ID_STOCK "\n"
           "pkg3=atmosphere/package3\n"
           "stock=1\n"
           "emummc_force_disable=1\n"
           "icon=bootloader/res/icon_switch.bmp\n"
           "\n"
           "{---- NOVA - Atmosph\xC3\xA8re ----}\n"
           "[NOVA Atmosph\xC3\xA8re (emuMMC)]\n"
           "id=" NOVA_ID_EMUMMC "\n"
           "pkg3=atmosphere/package3\n"
           "kip1=atmosphere/kips/*\n"
           "emummcforce=1\n"
           "icon=bootloader/res/icon_payload.bmp\n");

    if (pos + 1 >= out_size)
        return 0;
    return pos;
}

bool nova_hekate_set_boot_id(uint8_t *image, uint32_t size, const char *id)
{
    if (!image || size < NOVA_HEKATE_VER_OFFSET + 8)
        return false;

    uint32_t magic = (uint32_t)image[NOVA_HEKATE_VER_OFFSET] |
                     ((uint32_t)image[NOVA_HEKATE_VER_OFFSET + 1] << 8) |
                     ((uint32_t)image[NOVA_HEKATE_VER_OFFSET + 2] << 16) |
                     ((uint32_t)image[NOVA_HEKATE_VER_OFFSET + 3] << 24);
    if (magic != NOVA_HEKATE_MAGIC)
        return false;

    if (size < NOVA_HEKATE_CFG_OFFSET + NOVA_HEKATE_CFG_SIZE)
        return false;

    uint8_t *cfg = image + NOVA_HEKATE_CFG_OFFSET;
    nova_memset(cfg, 0, NOVA_HEKATE_CFG_SIZE);

    if (id && id[0])
    {
        cfg[HDR_BOOT_CFG] = BOOT_CFG_AUTOBOOT_EN | BOOT_CFG_FROM_ID;
        /* "0: Force go to menu, else boot that entry" -> non zero. */
        cfg[HDR_AUTOBOOT] = 1;
        cfg[HDR_AUTOB_LIST] = 0;
        cfg[HDR_EXTRA_CFG] = 0;
        nova_strncpy((char *)cfg + HDR_ID, id, 7);
        cfg[HDR_ID + 7] = '\0';
    }

    return true;
}

void nova_parse_hekate_version(const char *filename, char *out, uint32_t out_size)
{
    if (!out || !out_size)
        return;
    out[0] = '\0';
    if (!filename)
        return;

    /* Find the first digit run that looks like major.minor.patch. */
    for (const char *p = filename; *p; p++)
    {
        if (*p < '0' || *p > '9')
            continue;

        char ver[16];
        int n = 0;
        const char *q = p;
        int dots = 0;
        while (*q && n < (int)sizeof(ver) - 1)
        {
            if (*q >= '0' && *q <= '9')
                ver[n++] = *q;
            else if (*q == '.' && dots < 2)
            {
                ver[n++] = '.';
                dots++;
            }
            else
                break;
            q++;
        }
        ver[n] = '\0';

        if (dots >= 1 && n >= 3)
        {
            nova_cstr_copy(out, out_size, ver);
            return;
        }
    }
    nova_cstr_copy(out, out_size, "unknown");
}

bool nova_find_hekate(const nova_fs_t *fs, char *path, uint32_t path_size,
                      char *version, uint32_t version_size, bool *valid_out)
{
    if (!fs || !path || !path_size)
        return false;

    if (valid_out)
        *valid_out = false;

    path[0] = '\0';
    if (version && version_size)
        nova_cstr_copy(version, version_size, "unknown");

    static const char *dirs[] = {
        "",
        NOVA_HEKATE_PAYLOAD_DIR,
    };

    for (unsigned d = 0; d < sizeof(dirs) / sizeof(dirs[0]); d++)
    {
        nova_dir_iter_t *it = NULL;
        char name[128];
        const char *dir = dirs[d];
        int rc = fs->list_first(fs->ctx, dir[0] ? dir : "/",
                                NOVA_HEKATE_ROOT_PATTERN, name, sizeof(name), &it);
        while (rc == 0 && it)
        {
            char full[160];
            if (dir[0])
            {
                nova_cstr_copy(full, sizeof(full), dir);
                nova_strcat(full, "/");
            }
            else
            {
                full[0] = '\0';
            }
            nova_strcat(full, name);

            uint32_t size = 0;
            void *img = fs->read_file(fs->ctx, full, &size);
            bool valid = img && size <= NOVA_MAX_PAYLOAD_SIZE &&
                         nova_hekate_set_boot_id((uint8_t *)img, size, NULL);
            if (img)
                fs->free_file(fs->ctx, img);

            if (valid)
            {
                nova_cstr_copy(path, path_size, full);
                if (version && version_size)
                    nova_parse_hekate_version(name, version, version_size);
                if (valid_out)
                    *valid_out = true;
                fs->list_close(fs->ctx, it);
                return true;
            }

            /* Remember the first candidate so the UI can report it as invalid. */
            if (!path[0])
            {
                nova_cstr_copy(path, path_size, full);
                if (version && version_size)
                    nova_parse_hekate_version(name, version, version_size);
            }

            rc = fs->list_next(fs->ctx, it, name, sizeof(name));
        }
        if (it)
            fs->list_close(fs->ctx, it);
    }

    /* A candidate name was found even if the image itself is not hekate. */
    return path[0] != '\0';
}
